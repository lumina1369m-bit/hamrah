def rec(area, item, ok, note=''):
    R.append((area, item, ok, note))
async def ctx_for(b, w, lang='fa', seed=True):
    ctx = await b.new_context(viewport={'width': w, 'height': 844})
    await ctx.route(re.compile(r'https://(unpkg\.com|fonts\.googleapis\.com|fonts\.gstatic\.com|nominatim\.openstreetmap\.org|tile\.openstreetmap\.org).*'), lambda r: r.abort())
    await ctx.add_init_script("if(!sessionStorage.getItem('s')){%s localStorage.setItem('hamzaban_lang','%s');sessionStorage.setItem('s','1')}" % ("localStorage.setItem('hamzaban.user.v1',JSON.stringify({name:'علی',last:'رضایی',gender:'مرد',verified:false}));" if seed else '', lang))
    return ctx
