async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        try:
            await login_checks(b)
        except Exception as e: rec('ورود','اجرای آزمون ورود متوقف شد', False, str(e)[:150])
        try:
            await app_checks(b)
        except Exception as e: rec('اپ','اجرای آزمون اپ متوقف شد', False, str(e)[:150])
        await b.close()
    cur=None
    for a,i,ok,n in R:
        if a!=cur: print('\n## '+a); cur=a
        print(('  OK   ' if ok else '  FAIL ')+i+(('  ['+str(n)+']') if n else ''))
asyncio.run(main())
